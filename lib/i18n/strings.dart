  static String of(String locale, String key) =>
      _all[locale]?[key] ?? _en[key] ?? key;

  static String format(String locale, String key, Map<String, String> args) {
    var s = of(locale, key);
    args.forEach((k, v) => s = s.replaceAll('{$k}', v));
    return s;
  }
